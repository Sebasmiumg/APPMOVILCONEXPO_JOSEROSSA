-- Habilita actualización inmediata entre clientes autenticados. Las políticas
-- RLS existentes siguen delimitando las filas visibles para cada JWT.
do $$
declare
  v_table text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    return;
  end if;

  foreach v_table in array array['cuentas', 'categorias', 'movimientos', 'presupuestos', 'metas'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = v_table
    ) then
      execute format('alter publication supabase_realtime add table public.%I', v_table);
    end if;
  end loop;
end;
$$;
